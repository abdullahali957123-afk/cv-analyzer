PRIORITY_LABEL = {"high": "High priority", "medium": "Medium priority", "low": "Low priority"}


def _priority(kind, status):
    if kind == "required" and status == "missing":
        return "high"
    if kind == "required" and status == "partial":
        return "medium"
    if kind == "preferred" and status == "missing":
        return "medium"
    return "low"


def build_roadmap(required, preferred):
    """required/preferred: [{'skill': 'SQL', 'status': 'missing'}, ...]"""
    items = []
    for kind, lst in (("required", required), ("preferred", preferred)):
        for it in lst:
            skill, status = it.get("skill"), it.get("status")
            if status == "matched" or skill not in GUIDE:
                continue
            why, steps, project, portfolio, resources, time = GUIDE[skill]
            prio = _priority(kind, status)
            reason = "This is a %s skill for the job, and it is %s." % (
                "required" if kind == "required" else "preferred (nice to have)",
                "not found in your CV" if status == "missing"
                else "mentioned only in your projects or experience, not in Skills",
            )
            items.append({
                "skill": skill, "priority": prio, "priority_label": PRIORITY_LABEL[prio],
                "reason": reason, "why": why, "steps": steps, "project": project,
                "portfolio": portfolio, "resources": resources, "time": time,
            })
    order = {"high": 0, "medium": 1, "low": 2}
    items.sort(key=lambda x: order[x["priority"]])
    return {
        "items": items,
        "note": (
            "This roadmap only covers the skills that were missing in the job match. Time estimates are only estimates. "
            "Add a skill to your CV only after you have learned it; do not list skills you do not have."
        ),
    }
